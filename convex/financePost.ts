// إيجاد/إنشاء الفترة المالية الشهرية لتاريخ معيّن (yyyy-MM-dd).
async function ensurePeriod(ctx: Ctx, dateISO: string): Promise<Id<"finPeriods">> {
  const ym = dateISO.slice(0, 7);            // yyyy-MM
  const year = Number(dateISO.slice(0, 4));
  const all = await ctx.db.query("finPeriods").collect();
  const found = all.find((p: any) => p.name === ym);
  if (found) return found._id;
  const mm = dateISO.slice(5, 7);
  const lastDay = new Date(year, Number(mm), 0).getDate();
  return await ctx.db.insert("finPeriods", {
    name: ym,
    fiscalYear: year,
    startDate: `${ym}-01`,
    endDate: `${ym}-${String(lastDay).padStart(2, "0")}`,
    status: "open",
    createdAt: Date.now(),
  });
}

// هل الفترة تسمح بالترحيل؟
async function assertPeriodOpen(ctx: Ctx, periodId: Id<"finPeriods">) {
  const p = await ctx.db.get(periodId);
  if (p && p.status !== "open") {
    throw new Error(`الفترة ${p.name} مقفولة — لا يمكن الترحيل عليها`);
  }
}

// الرقم المتسلسل التالي للقيد.
async function nextJournalNumber(ctx: Ctx): Promise<string> {
  let c = await ctx.db.query("finCounters").withIndex("by_key", (q: any) => q.eq("key", "journal")).first();
  if (!c) {
    const id = await ctx.db.insert("finCounters", { key: "journal", prefix: "JV-", value: 1 });
    c = await ctx.db.get(id);
    return `JV-${String(1).padStart(6, "0")}`;
  }
  const next = (c.value || 0) + 1;
  await ctx.db.patch(c._id, { value: next });
  return `${c.prefix || "JV-"}${String(next).padStart(6, "0")}`;
}

// حساب بالكود (كاش) — للترحيل التلقائي.
async function accByCode(ctx: Ctx, code: string): Promise<Id<"finAccounts"> | null> {
  const a = await ctx.db.query("finAccounts").withIndex("by_code", (q: any) => q.eq("code", code)).first();
  return a?._id ?? null;
}

type LineIn = {
  accountId: Id<"finAccounts">;
  debit?: number;
  credit?: number;
  description?: string;
  costCenterId?: Id<"finCostCenters">;
  partyType?: string;
  partyId?: string;
  documentRef?: string;
};

// إنشاء قيد كامل (رأس + أسطر) بعد التحقق من التوازن. الدالة الأساسية لكل ترحيل.
export async function postEntry(
  ctx: Ctx,
  opts: {
    entryDate: string;
    description: string;
    lines: LineIn[];
    journalType: string;
    branchId?: Id<"posBranches">;
    costCenterId?: Id<"finCostCenters">;
    sourceType?: string;
    sourceId?: string;
    isAutoGenerated?: boolean;
    status?: "draft" | "posted";
    createdBy?: Id<"users">;
    notes?: string;
  },
): Promise<{ entryId: Id<"finJournalEntries">; entryNumber: string }> {
  const lines = (opts.lines || []).filter((l) => (l.debit || 0) !== 0 || (l.credit || 0) !== 0);
  if (lines.length < 2) throw new Error("القيد يحتاج سطرين على الأقل");
  const round = (n: number) => Math.round((n || 0) * 1000) / 1000;
  const totalDebit = round(lines.reduce((s, l) => s + (l.debit || 0), 0));
  const totalCredit = round(lines.reduce((s, l) => s + (l.credit || 0), 0));
  if (Math.abs(totalDebit - totalCredit) > 0.01) {
    throw new Error(`القيد غير متوازن: مدين ${totalDebit} ≠ دائن ${totalCredit}`);
  }
  if (totalDebit === 0) throw new Error("القيد بقيمة صفر");

  const periodId = await ensurePeriod(ctx, opts.entryDate);
  await assertPeriodOpen(ctx, periodId);
  const entryNumber = await nextJournalNumber(ctx);
  const now = Date.now();
  const status = opts.status || "posted";

  const entryId = await ctx.db.insert("finJournalEntries", {
    entryNumber,
    journalType: opts.journalType as any,
    entryDate: opts.entryDate,
    periodId,
    costCenterId: opts.costCenterId,
    branchId: opts.branchId,
    description: opts.description,
    totalDebit,
    totalCredit,
    postingStatus: status,
    isAutoGenerated: !!opts.isAutoGenerated,
    sourceType: opts.sourceType,
    sourceId: opts.sourceId,
    postedBy: status === "posted" ? opts.createdBy : undefined,
    postedAt: status === "posted" ? now : undefined,
    createdBy: opts.createdBy,
    notes: opts.notes,
    createdAt: now,
  });

  let i = 1;
  for (const l of lines) {
    await ctx.db.insert("finJournalLines", {
      entryId,
      lineNumber: i++,
      accountId: l.accountId,
      description: l.description,
      costCenterId: l.costCenterId ?? opts.costCenterId,
      debit: round(l.debit || 0),
      credit: round(l.credit || 0),
      partyType: l.partyType,
      partyId: l.partyId,
      documentRef: l.documentRef,
      createdAt: now,
    });
  }
  return { entryId, entryNumber };
}

// ---------- الترحيل التلقائي: فاتورة POS مدفوعة ----------
// يُستدعى بأمان بعد الدفع. idempotent عبر (sourceType, sourceId).
// أي خطأ لا يكسر البيع — يُبتلع ويُسجَّل.
export async function autoPostPosTicket(ctx: Ctx, ticketId: Id<"posTickets">): Promise<boolean> {
  try {
    const t: any = await ctx.db.get(ticketId);
    if (!t || t.status !== "PAID") return false;
    if (t.isNonRevenue) return false; // خارج الإيراد لا يُرحَّل كمبيعات

    // منع التكرار
    const existing = await ctx.db
      .query("finJournalEntries")
      .withIndex("by_source", (q: any) => q.eq("sourceType", "posTicket").eq("sourceId", String(ticketId)))
      .first();
    if (existing) return false;

    const date = new Date(t.paidAt || t.createdAt || Date.now()).toISOString().slice(0, 10);
    const total = Number(t.total || 0);
    if (total <= 0) return false;

    // الحسابات
    const salesAcc = await accByCode(ctx, "4110");        // مبيعات المطعم
    const vatAcc = await accByCode(ctx, "2130");          // ض.ق.م مستحقة
    const cashAcc = await accByCode(ctx, "1111");         // درج الكاشير
    const cardAcc = await accByCode(ctx, "1130");         // بطاقات تحت التحصيل
    const platformAcc = await accByCode(ctx, "1140");     // منصّات تحت التحصيل
    const discountAcc = await accByCode(ctx, "4195");     // خصومات ممنوحة
    if (!salesAcc || !cashAcc) return false;

    const tax = Number(t.tax || 0);
    const discount = Number(t.discount || 0);
    const netRevenue = total - tax; // الإيراد صافي الضريبة

    // توزيع المدفوعات على الحسابات (كاش/كارت/منصّة)
    const payments: Array<{ method: string; amount: number }> = Array.isArray(t.payments) && t.payments.length
      ? t.payments
      : [{ method: String(t.paymentMethod || "cash"), amount: total }];

    const methodAcc = (m: string): Id<"finAccounts"> => {
      const s = String(m || "").toLowerCase();
      if (s.includes("card") || s.includes("visa") || s.includes("shabaka") || s.includes("شبكة")) return cardAcc || cashAcc!;
      if (["talabat", "snoonu", "rafeeq", "keeta", "deliveroo"].some((p) => s.includes(p))) return platformAcc || cardAcc || cashAcc!;
      return cashAcc!; // cash / transfer / staff → صندوق
    };

    const lines: LineIn[] = [];
    // مدين: طرق الدفع
    for (const p of payments) {
      const amt = Number(p.amount || 0);
      if (amt <= 0) continue;
      lines.push({ accountId: methodAcc(p.method), debit: amt, description: `تحصيل ${p.method}` });
    }
    // مدين: الخصم الممنوح (إن وُجد)
    if (discount > 0 && discountAcc) {
      lines.push({ accountId: discountAcc, debit: discount, description: "خصم ممنوح" });
    }
    // دائن: المبيعات (صافي الضريبة، ومضاف إليه الخصم لأن الإيراد الإجمالي قبل الخصم)
    lines.push({ accountId: salesAcc, credit: netRevenue + discount, description: `فاتورة #${t.ticketNumber}` });
    // دائن: الضريبة
    if (tax > 0 && vatAcc) lines.push({ accountId: vatAcc, credit: tax, description: "ض.ق.م" });

    await postEntry(ctx, {
      entryDate: date,
      description: `مبيعات POS — فاتورة #${t.ticketNumber}`,
      lines,
      journalType: "auto_sales",
      branchId: t.branchId,
      sourceType: "posTicket",
      sourceId: String(ticketId),
      isAutoGenerated: true,
      createdBy: t.cashierId,
    });
    return true;
  } catch (e) {
    console.error("autoPostPosTicket failed (non-blocking):", String(e));
    return false;
  }
}

/** Reverse the accounting effect of a paid POS ticket exactly once. */
export async function autoReversePosTicket(
  ctx: Ctx,
  ticketId: Id<"posTickets">,
  reason: string,
  createdBy?: Id<"users">,
): Promise<boolean> {
  try {
    const original: any = await ctx.db
      .query("finJournalEntries")
      .withIndex("by_source", (q: any) => q.eq("sourceType", "posTicket").eq("sourceId", String(ticketId)))
      .first();
    if (!original || original.postingStatus !== "posted" || original.reversalEntryId) return false;
    const lines = await ctx.db.query("finJournalLines").withIndex("by_entry", (q: any) => q.eq("entryId", original._id)).collect();
    const rev = await postEntry(ctx, {
      entryDate: new Date().toISOString().slice(0, 10),
      description: `عكس ${original.description} — ${reason}`,
      journalType: "reversing",
      branchId: original.branchId,
      costCenterId: original.costCenterId,
      sourceType: "posTicketReversal",
      sourceId: String(ticketId),
      isAutoGenerated: true,
      createdBy,
      lines: lines.map((l: any) => ({
        accountId: l.accountId,
        debit: l.credit,
        credit: l.debit,
        description: `عكس ${l.description || ""}`,
        costCenterId: l.costCenterId,
        partyType: l.partyType,
        partyId: l.partyId,
        documentRef: l.documentRef,
      })),
    });
    await ctx.db.patch(original._id, { postingStatus: "reversed", reversalEntryId: rev.entryId });
    await ctx.db.patch(rev.entryId, { reversedEntryId: original._id });
    return true;
  } catch (e) {
    console.error("autoReversePosTicket failed (non-blocking):", String(e));
    return false;
  }
}

async function reversePostedSource(ctx: Ctx, sourceType: string, sourceId: string, reason: string, createdBy?: Id<"users">) {
  const matches = await ctx.db.query("finJournalEntries")
    .withIndex("by_source", (q: any) => q.eq("sourceType", sourceType).eq("sourceId", sourceId)).collect();
  const entry: any = matches.find((e: any) => e.postingStatus === "posted" && !e.reversalEntryId);
  if (!entry) return false;
  const lines = await ctx.db.query("finJournalLines").withIndex("by_entry", (q: any) => q.eq("entryId", entry._id)).collect();
  const rev = await postEntry(ctx, {
    entryDate: new Date().toISOString().slice(0, 10),
    description: `عكس ${entry.description} — ${reason}`,
    journalType: "reversing",
    isAutoGenerated: true,
    createdBy,
    lines: lines.map((l: any) => ({ accountId: l.accountId, debit: l.credit, credit: l.debit, description: `عكس ${l.description || ""}`, partyType: l.partyType, partyId: l.partyId, documentRef: l.documentRef })),
  });
  await ctx.db.patch(entry._id, { postingStatus: "reversed", reversalEntryId: rev.entryId });
  await ctx.db.patch(rev.entryId, { reversedEntryId: entry._id });
  return true;
}

/** Accrual invoice for an outlet: receivable + discount against gross outlet revenue. */
export async function autoPostGymOrder(ctx: Ctx, orderId: Id<"gymOrders">, createdBy?: Id<"users">): Promise<boolean> {
  try {
    const order: any = await ctx.db.get(orderId);
    if (!order || order.isVoid) return false;
    const matches = await ctx.db.query("finJournalEntries")
      .withIndex("by_source", (q: any) => q.eq("sourceType", "gymOrder").eq("sourceId", String(orderId))).collect();
    if (matches.some((e: any) => e.postingStatus === "posted" && !e.reversalEntryId)) return false;
    const receivable = await accByCode(ctx, "1150");
    const revenue = await accByCode(ctx, "4140");
    const discountAcc = await accByCode(ctx, "4195");
    if (!receivable || !revenue) return false;
    const total = Number(order.total || 0);
    const subtotal = Number(order.subtotal || total);
    const discount = Math.max(0, Number(order.discountAmount || subtotal - total));
    if (total <= 0) return false;
    const lines: LineIn[] = [
      { accountId: receivable, debit: total, description: "ذمة المنفذ", partyType: "outlet", partyId: String(order.gymId), documentRef: String(orderId) },
      { accountId: revenue, credit: subtotal, description: "مبيعات المنفذ", partyType: "outlet", partyId: String(order.gymId), documentRef: String(orderId) },
    ];
    if (discount > 0 && discountAcc) lines.push({ accountId: discountAcc, debit: discount, description: "خصم المنفذ", partyType: "outlet", partyId: String(order.gymId) });
    await postEntry(ctx, { entryDate: order.date, description: `فاتورة منفذ ${String(orderId).slice(-6)}`, lines, journalType: "auto_gym", sourceType: "gymOrder", sourceId: String(orderId), isAutoGenerated: true, createdBy });
    return true;
  } catch (e) {
    console.error("autoPostGymOrder failed (non-blocking):", String(e));
    return false;
  }
}

export async function autoReverseGymOrder(ctx: Ctx, orderId: Id<"gymOrders">, reason: string, createdBy?: Id<"users">) {
  return await reversePostedSource(ctx, "gymOrder", String(orderId), reason, createdBy);
}

/** Outlet returns reduce both the receivable and net sales. */
export async function autoPostGymReturn(ctx: Ctx, returnId: Id<"gymReturnBatches">, createdBy?: Id<"users">): Promise<boolean> {
  try {
    const batch: any = await ctx.db.get(returnId);
    if (!batch || Number(batch.wasteValue || 0) <= 0) return false;
    const existing = await ctx.db.query("finJournalEntries")
      .withIndex("by_source", (q: any) => q.eq("sourceType", "gymReturn").eq("sourceId", String(returnId))).first();
    if (existing) return false;
    const returnsAcc = await accByCode(ctx, "4190");
    const receivable = await accByCode(ctx, "1150");
    if (!returnsAcc || !receivable) return false;
    const amount = Number(batch.wasteValue);
    await postEntry(ctx, {
      entryDate: batch.returnDate,
      description: `مرتجع منفذ ${String(returnId).slice(-6)}`,
      journalType: "auto_gym",
      sourceType: "gymReturn",
      sourceId: String(returnId),
      isAutoGenerated: true,
      createdBy,
      lines: [
        { accountId: returnsAcc, debit: amount, description: "مردودات مبيعات منفذ", partyType: "outlet", partyId: String(batch.gymId), documentRef: String(returnId) },
        { accountId: receivable, credit: amount, description: "تخفيض ذمة المنفذ", partyType: "outlet", partyId: String(batch.gymId), documentRef: String(returnId) },
      ],
    });
    return true;
  } catch (e) {
    console.error("autoPostGymReturn failed (non-blocking):", String(e));
    return false;
  }
}

