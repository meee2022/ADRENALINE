const FINANCE_ROLES = ["ACCOUNTANT", "FINANCE_MANAGER"];
const FINANCE_PERMISSIONS = ["/finance"];

async function requireFinance(ctx: Ctx, token?: string) {
  return await requireRoleOrPermission(ctx, token, {
    roles: FINANCE_ROLES,
    permissions: FINANCE_PERMISSIONS,
  });
}

async function auditFinance(ctx: Ctx, actor: any, action: string, entityId?: string, details?: any) {
  const user: any = actor?.userId ? await ctx.db.get(actor.userId as any) : null;
  await ctx.db.insert("auditLog", {
    actorUserId: actor?.userId as any,
    actorName: user?.name,
    actorRole: actor?.role,
    action,
    entityType: "finance",
    entityId,
    details: details ? JSON.stringify(details) : undefined,
    createdAt: Date.now(),
  });
}

