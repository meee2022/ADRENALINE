// ---------- عكس قيد مُرحَّل (بدل الحذف — للحفاظ على سجل التدقيق) ----------
export const reverseEntry = mutation({
  args: { entryId: v.id("finJournalEntries"), reason: v.string(), sessionToken: v.optional(v.string()) },
  handler: async (ctx, args) => {
    const actor = await requireFinance(ctx, args.sessionToken);
    const entry: any = await ctx.db.get(args.entryId);
    if (!entry) throw new Error("القيد غير موجود");
    if (entry.postingStatus !== "posted") throw new Error("لا يمكن عكس قيد غير مُرحَّل");
    if (entry.reversalEntryId) throw new Error("القيد معكوس بالفعل");
    const lines = await ctx.db.query("finJournalLines").withIndex("by_entry", (q) => q.eq("entryId", args.entryId)).collect();
    const today = new Date().toISOString().slice(0, 10);
    const rev = await postEntry(ctx, {
      entryDate: today,
      description: `عكس: ${entry.description} — ${args.reason}`,
      journalType: "reversing",
      branchId: entry.branchId,
      costCenterId: entry.costCenterId,
      isAutoGenerated: false,
      createdBy: actor.userId as any,
      lines: lines.map((l: any) => ({
        accountId: l.accountId,
        debit: l.credit,   // معكوس
        credit: l.debit,
        description: `عكس ${l.description || ""}`,
        costCenterId: l.costCenterId,
        partyType: l.partyType,
        partyId: l.partyId,
      })),
    });
    await ctx.db.patch(entry._id, { postingStatus: "reversed", reversalEntryId: rev.entryId });
    await ctx.db.patch(rev.entryId, { reversedEntryId: entry._id });
    await auditFinance(ctx, actor, "FINANCE_ENTRY_REVERSED", String(entry._id), { reversalEntryId: String(rev.entryId), reason: args.reason });
    return rev;
  },
});

// ---------- استعلام: القيود (مع فلاتر) ----------
export const listJournalEntries = query({
  args: { limit: v.optional(v.number()), fromDate: v.optional(v.string()), toDate: v.optional(v.string()), sessionToken: v.optional(v.string()) },
  handler: async (ctx, args) => {
    await requireFinance(ctx, args.sessionToken);
    let entries = await ctx.db.query("finJournalEntries").withIndex("by_date").order("desc").collect();
    if (args.fromDate) entries = entries.filter((e) => e.entryDate >= args.fromDate!);
    if (args.toDate) entries = entries.filter((e) => e.entryDate <= args.toDate!);
    entries = entries.slice(0, args.limit ?? 200);
    // إرفاق الأسطر
    const out = [];
    for (const e of entries) {
      const lines = await ctx.db.query("finJournalLines").withIndex("by_entry", (q) => q.eq("entryId", e._id)).collect();
      out.push({ ...e, lines });
    }
    return out;
  },
});
