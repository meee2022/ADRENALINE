/** Inventory issue, waste, or count variance valued at FIFO cost by the inventory module. */
export async function autoPostInventoryMovement(ctx: Ctx, opts: {
  movementId: Id<"inventoryMovements">;
  date: string;
  amount: number;
  kind: "consume" | "waste" | "adjust";
  quantity: number;
  itemId: Id<"inventoryItems">;
  createdBy?: Id<"users">;
}) {
  try {
    if (opts.amount <= 0 || opts.quantity === 0) return false;
    const sourceId = String(opts.movementId);
    const existing = await ctx.db.query("finJournalEntries")
      .withIndex("by_source", (q: any) => q.eq("sourceType", "inventoryMovement").eq("sourceId", sourceId)).first();
    if (existing) return false;
    const inventory = await accByCode(ctx, "1160");
    const expense = await accByCode(ctx, opts.kind === "consume" ? "5110" : opts.kind === "waste" ? "5130" : "5150");
    if (!inventory || !expense) return false;
    const label = opts.kind === "consume" ? "استهلاك مواد المطبخ" : opts.kind === "waste" ? "هالك وتالف مخزون" : "فرق جرد المخزون";
    const increase = opts.kind === "adjust" && opts.quantity > 0;
    await postEntry(ctx, {
      entryDate: opts.date,
      description: label,
      journalType: "auto_inventory",
      sourceType: "inventoryMovement",
      sourceId,
      isAutoGenerated: true,
      createdBy: opts.createdBy,
      lines: increase
        ? [
            { accountId: inventory, debit: opts.amount, description: label, documentRef: String(opts.itemId) },
            { accountId: expense, credit: opts.amount, description: label, documentRef: String(opts.itemId) },
          ]
        : [
            { accountId: expense, debit: opts.amount, description: label, documentRef: String(opts.itemId) },
            { accountId: inventory, credit: opts.amount, description: label, documentRef: String(opts.itemId) },
          ],
    });
    return true;
  } catch (e) {
    console.error("autoPostInventoryMovement failed (non-blocking):", String(e));
    return false;
  }
}

export const postPayrollMonth = mutation({
  args: { month: v.string(), sessionToken: v.optional(v.string()) },
  handler: async (ctx, args) => {
    const actor = await requireFinance(ctx, args.sessionToken);
    if (!/^\d{4}-\d{2}$/.test(args.month)) throw new Error("صيغة الشهر غير صحيحة");
    const existing = await ctx.db.query("finJournalEntries")
      .withIndex("by_source", (q: any) => q.eq("sourceType", "payrollMonth").eq("sourceId", args.month)).collect();
    if (existing.some((entry: any) => entry.postingStatus === "posted" && !entry.reversalEntryId)) {
      throw new Error("رواتب هذا الشهر رُحّلت بالفعل");
    }
    const rows = (await ctx.db.query("payroll").withIndex("by_month", (q: any) => q.eq("month", args.month)).collect()).filter((r: any) => !r.isVoid);
    if (!rows.length) throw new Error("لا توجد رواتب في هذا الشهر");
    let salary = 0, overtime = 0, paid = 0, advance = 0;
    for (const row of rows as any[]) {
      const monthly = (Number(row.basic || 0) + Number(row.allowance || 0)) * Math.min(Number(row.days || 0), 31) / 31;
      salary += Math.round(monthly);
      overtime += Number(row.overtime || 0);
      paid += Number(row.paid || 0);
      advance += Number(row.advance || 0);
    }
    const total = salary + overtime;
    const cashPaid = Math.min(total, paid + advance);
    const accrued = Math.max(0, total - cashPaid);
    const salaryAcc = await accByCode(ctx, "6110");
    const overtimeAcc = await accByCode(ctx, "6115");
    const accruedAcc = await accByCode(ctx, "2120");
    const cashAcc = await accByCode(ctx, "1110");
    if (!salaryAcc || !overtimeAcc || !accruedAcc || !cashAcc) throw new Error("حسابات الرواتب الأساسية غير مكتملة");
    const lines: LineIn[] = [{ accountId: salaryAcc, debit: salary, description: `رواتب ${args.month}` }];
    if (overtime > 0) lines.push({ accountId: overtimeAcc, debit: overtime, description: `إضافي ومكافآت ${args.month}` });
    if (cashPaid > 0) lines.push({ accountId: cashAcc, credit: cashPaid, description: "رواتب وسلف مدفوعة" });
    if (accrued > 0) lines.push({ accountId: accruedAcc, credit: accrued, description: "رواتب مستحقة" });
    const result = await postEntry(ctx, {
      entryDate: `${args.month}-${String(new Date(Number(args.month.slice(0, 4)), Number(args.month.slice(5, 7)), 0).getDate()).padStart(2, "0")}`,
      description: `اعتماد رواتب ${args.month}`,
      lines, journalType: "auto_payroll", sourceType: "payrollMonth", sourceId: args.month,
      isAutoGenerated: true, createdBy: actor.userId as any,
    });
    await auditFinance(ctx, actor, "PAYROLL_MONTH_POSTED", String(result.entryId), { month: args.month, employees: rows.length, total, cashPaid, accrued });
    return { ...result, employees: rows.length, total, cashPaid, accrued };
  },
});

/** Safe, repeatable migration of historical operational documents into the ledger. */
export const reconcileOperationalLedger = mutation({
  args: { sessionToken: v.optional(v.string()) },
  handler: async (ctx, args) => {
    const actor = await requireFinance(ctx, args.sessionToken);
    const result = { posPosted: 0, posReversed: 0, outletsPosted: 0, outletReturnsPosted: 0 };
    const tickets = await ctx.db.query("posTickets").collect();
    for (const ticket of tickets as any[]) {
      if (ticket.status === "PAID" && await autoPostPosTicket(ctx, ticket._id)) result.posPosted++;
      if (["REFUNDED", "VOID"].includes(ticket.status) && await autoReversePosTicket(ctx, ticket._id, "مطابقة تاريخية", actor.userId as any)) result.posReversed++;
    }
    const orders = await ctx.db.query("gymOrders").collect();
    for (const order of orders as any[]) {
      if (!order.isVoid && await autoPostGymOrder(ctx, order._id, actor.userId as any)) result.outletsPosted++;
      if (order.isVoid) await autoReverseGymOrder(ctx, order._id, "طلب ملغى", actor.userId as any);
    }
    const returns = await ctx.db.query("gymReturnBatches").collect();
    for (const batch of returns as any[]) if (await autoPostGymReturn(ctx, batch._id, actor.userId as any)) result.outletReturnsPosted++;
    await auditFinance(ctx, actor, "FINANCE_OPERATIONAL_RECONCILIATION", undefined, result);
    return result;
  },
});

// ترحيل دفعي لكل الفواتير المدفوعة غير المرحّلة (آمن، يُعاد تشغيله).
export const backfillPosTickets = mutation({
  args: { limit: v.optional(v.number()), sessionToken: v.optional(v.string()) },
  handler: async (ctx, args) => {
    await requireFinance(ctx, args.sessionToken);
    const paid = await ctx.db.query("posTickets").withIndex("by_status", (q) => q.eq("status", "PAID")).collect();
    let posted = 0, skipped = 0;
    const lim = args.limit ?? 100000;
    for (const t of paid) {
      if (posted >= lim) break;
      const ok = await autoPostPosTicket(ctx, t._id);
      ok ? posted++ : skipped++;
    }
    return { paidTickets: paid.length, posted, skipped };
  },
});

